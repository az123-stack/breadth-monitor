def main():
    out = Path(__file__).resolve().parent.parent / "data" / "themes.csv"
    rows = []
    for line in THEMES.strip().splitlines():
        theme, etfs, members = [p.strip() for p in line.split("|")]
        for t in etfs.split():
            rows.append({"theme": theme, "ticker": t, "role": "etf"})
        for t in members.split():
            rows.append({"theme": theme, "ticker": t, "role": "member"})
    out.parent.mkdir(exist_ok=True)
    with out.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["theme", "ticker", "role"])
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {len(rows)} rows, {len({r['theme'] for r in rows})} themes -> {out}")


if __name__ == "__main__":
    main()
